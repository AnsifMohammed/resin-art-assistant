// Helper to filter and sort customers
export function filterCustomers(
  items: ExtendedCustomer[],
  options: {
    tab: "all" | "favourites" | "priority" | "repeat" | "new" | "vip";
    channel: "all" | "whatsapp" | "instagram";
    city: string;
    spendRange: "all" | "low" | "medium" | "high";
    search: string;
    sortBy: "spend_desc" | "spend_asc" | "orders_desc" | "recent" | "name_asc";
  }
): ExtendedCustomer[] {
  return items
    .filter((c) => {
      // Tab filter
      if (options.tab === "favourites" && !c.isFavourite) return false;
      if (options.tab === "priority" && !c.isPriority) return false;
      if (options.tab === "repeat" && c.ordersCount < 2) return false;
      if (options.tab === "new" && c.ordersCount > 1) return false;
      if (options.tab === "vip" && c.vipTier !== "Platinum") return false;

      // Channel filter
      if (options.channel !== "all" && c.channel !== options.channel) return false;

      // City filter
      if (options.city !== "all" && c.city.toLowerCase() !== options.city.toLowerCase()) return false;

      // Spend range filter
      if (options.spendRange === "low" && c.totalSpend > 2000) return false;
      if (options.spendRange === "medium" && (c.totalSpend < 2000 || c.totalSpend > 5000)) return false;
      if (options.spendRange === "high" && c.totalSpend <= 5000) return false;

      // Search query
      if (options.search.trim()) {
        const q = options.search.toLowerCase();
        return (
          c.name.toLowerCase().includes(q) ||
          c.handleOrPhone.toLowerCase().includes(q) ||
          c.city.toLowerCase().includes(q) ||
          (c.notes && c.notes.toLowerCase().includes(q))
        );
      }

      return true;
    })
    .sort((a, b) => {
      if (options.sortBy === "spend_desc") return b.totalSpend - a.totalSpend;
      if (options.sortBy === "spend_asc") return a.totalSpend - b.totalSpend;
      if (options.sortBy === "orders_desc") return b.ordersCount - a.ordersCount;
      if (options.sortBy === "name_asc") return a.name.localeCompare(b.name);
      return 0;
    });
}
